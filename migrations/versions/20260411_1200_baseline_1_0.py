from collections.abc import Sequence

from alembic import op

import neozen.storage.sqlalchemy  # noqa: F401  side-effect: registers every table
from neozen.storage.sqlalchemy.base import Base

# revision identifiers, used by Alembic.
revision: str = "1_0_baseline"
down_revision: str | None = None
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None


def upgrade() -> None:
    """Create every table NeoZen 1.0 ships."""
    bind = op.get_bind()
    Base.metadata.create_all(bind=bind)


def downgrade() -> None:
    """Drop every table NeoZen 1.0 ships."""
    bind = op.get_bind()
    Base.metadata.drop_all(bind=bind)
