"""1.0 baseline schema

Revision ID: 1_0_baseline
Revises:
Create Date: 2026-04-11 12:00:00 UTC

This is the **baseline migration** for the NeoZen 1.0 release line.
It creates the entire SQLAlchemy schema as it stands at 1.0 by
delegating to ``Base.metadata.create_all``. Subsequent migrations
should be hand-written or autogenerated against this baseline.

Why delegate to ``create_all`` instead of hard-coding column lists?
The 1.0 schema is large (subjects, sessions, tokens, OAuth clients,
SCIM, audit, groups, organizations, OIDC consents, magic links,
WebAuthn credentials, and more). Maintaining a parallel
hand-written description in this file would be a maintenance trap
and a source of subtle drift between models and migrations. Using
``create_all`` here guarantees the baseline is exactly the schema
the application code declares.

After 1.0, schema changes should be normal Alembic revisions —
``alembic revision --autogenerate -m "describe change"`` — that
diff against this baseline. The autogenerator works fine even
though the baseline itself is delegated.
"""

